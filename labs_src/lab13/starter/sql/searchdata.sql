-- =====================================================================
-- Лабораторная работа №13. Большой объём «живых» текстов для проверки поиска.
-- В bigdata.sql (лабораторная работа №10) все названия одинаковые («Тестовая задача №123»), поиск по ним бесполезен.
-- Здесь названия и описания собираются из слов случайным образом, поэтому одни слова встречаются часто, другие редко,
-- как в настоящих задачах. Загрузка: php bin/load-searchdata.php 100000 (число задач можно указать).
-- Внимание: после загрузки автотесты запускать не нужно без php bin/reset-db.php (они рассчитаны на 7 задач).
-- =====================================================================

SELECT setseed(0.37);                                    -- одинаковое «случайное» заполнение при каждом запуске

WITH new_projects AS (
    INSERT INTO projects (title, description)
    SELECT 'Проект ' || (ARRAY['Альфа', 'Бета', 'Гамма', 'Дельта', 'Омега', 'Орион', 'Сириус', 'Вега', 'Атлас', 'Титан'])[1 + (i - 1) % 10] || ' ' || i,
           'Сгенерированный проект для проверки поиска'
    FROM generate_series(1, 30) AS i
    RETURNING id
), project_ids AS (
    SELECT array_agg(id) AS ids FROM new_projects
), words AS (
    SELECT ARRAY['Подготовить', 'Проверить', 'Согласовать', 'Исправить', 'Настроить', 'Описать', 'Обновить', 'Реализовать',
                 'Протестировать', 'Развернуть', 'Собрать', 'Проанализировать', 'Оптимизировать', 'Перенести', 'Удалить', 'Добавить'] AS verbs,
           ARRAY['квартальный', 'срочный', 'клиентский', 'внутренний', 'технический', 'финансовый', 'мобильный', 'новый', 'старый', 'пользовательский',
                 'годовой', 'ежедневный', 'тестовый', 'архивный', 'сводный', 'пробный'] AS adjs,
           ARRAY['отчёт', 'договор', 'экран', 'сервер', 'каталог', 'заказ', 'платёж', 'макет', 'сертификат', 'интерфейс', 'бюджет', 'график',
                 'сценарий', 'доступ', 'шаблон', 'справочник', 'модуль', 'прайс-лист', 'регламент', 'протокол'] AS nouns,
           ARRAY['по продажам', 'для отдела кадров', 'для партнёров', 'после релиза', 'до конца месяца', 'вместе с командой дизайна',
                 'по итогам встречи', 'для мобильного приложения', 'в личном кабинете', 'на сайте компании', 'в системе учёта', 'для новых клиентов'] AS tails,
           ARRAY['Необходимо учесть замечания заказчика и согласовать изменения с руководителем проекта.',
                 'Работа должна быть завершена до конца недели, иначе сдвинется выпуск версии.',
                 'Результат нужно выложить в общий каталог и отправить ссылку всей команде.',
                 'Сначала проверьте, как это работает сейчас, затем опишите найденные ошибки.',
                 'Подробности обсуждались на планёрке, записи лежат в рабочем чате.',
                 'Если возникнут вопросы по срокам, обратитесь к менеджеру проекта.',
                 'Проверьте также работу на телефоне и в старых версиях браузера.',
                 'Данные для расчётов возьмите из последней выгрузки бухгалтерии.',
                 'Нужно подготовить краткую сводку и показать её на встрече с клиентом.',
                 'Файлы с исходными материалами приложены к письму от партнёров.'] AS notes
), numbered AS (
    SELECT g.i, random() AS r0, random() AS r1, random() AS r2, random() AS r3, random() AS r4, random() AS r5, random() AS r6, random() AS r7, random() AS r8,
           random() AS r9, random() AS r10
    FROM generate_series(1, :count) AS g(i)
)
INSERT INTO tasks (project_id, title, description, status, priority, due_date, created_at)
SELECT p.ids[1 + floor(n.r0 * cardinality(p.ids))::int],
       w.verbs[1 + floor(n.r2 * 16)::int] || ' ' || w.adjs[1 + floor(n.r3 * 16)::int] || ' ' || w.nouns[1 + floor(n.r4 * 20)::int]
           || CASE WHEN n.r5 < 0.5 THEN ' ' || w.tails[1 + floor(n.r6 * 12)::int] ELSE '' END,
       CASE WHEN n.r7 < 0.3 THEN '' ELSE w.notes[1 + floor(n.r8 * 10)::int] || CASE WHEN n.r9 < 0.5 THEN ' ' || w.notes[1 + floor(n.r10 * 10)::int] ELSE '' END END,
       CASE WHEN n.r1 < 0.60 THEN 'done' WHEN n.r1 < 0.85 THEN 'in_progress' ELSE 'new' END,                  -- 60% выполнено, 25% в работе
       (ARRAY['low', 'medium', 'high'])[1 + floor(n.r9 * 3)::int],
       DATE '2025-01-01' + floor(n.r10 * 730)::int,
       TIMESTAMP '2025-01-01' + n.r8 * INTERVAL '640 days'
FROM numbered n, words w, project_ids p;

ANALYZE;                                                 -- обновить статистику для планировщика запросов
